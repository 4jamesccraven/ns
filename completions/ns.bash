_ns() {
    local i cur prev opts cmd
    COMPREPLY=()
    if [[ "${BASH_VERSINFO[0]}" -ge 4 ]]; then
        cur="$2"
    else
        cur="${COMP_WORDS[COMP_CWORD]}"
    fi
    prev="$3"
    cmd=""
    opts=""

    for i in "${COMP_WORDS[@]:0:COMP_CWORD}"
    do
        case "${cmd},${i}" in
            ",$1")
                cmd="ns"
                ;;
            ns,edit)
                cmd="ns__subcmd__edit"
                ;;
            ns,help)
                cmd="ns__subcmd__help"
                ;;
            ns,homepage)
                cmd="ns__subcmd__homepage"
                ;;
            ns,run)
                cmd="ns__subcmd__run"
                ;;
            ns,search)
                cmd="ns__subcmd__search"
                ;;
            ns,shell)
                cmd="ns__subcmd__shell"
                ;;
            ns,source)
                cmd="ns__subcmd__source"
                ;;
            ns__subcmd__help,edit)
                cmd="ns__subcmd__help__subcmd__edit"
                ;;
            ns__subcmd__help,help)
                cmd="ns__subcmd__help__subcmd__help"
                ;;
            ns__subcmd__help,homepage)
                cmd="ns__subcmd__help__subcmd__homepage"
                ;;
            ns__subcmd__help,run)
                cmd="ns__subcmd__help__subcmd__run"
                ;;
            ns__subcmd__help,search)
                cmd="ns__subcmd__help__subcmd__search"
                ;;
            ns__subcmd__help,shell)
                cmd="ns__subcmd__help__subcmd__shell"
                ;;
            ns__subcmd__help,source)
                cmd="ns__subcmd__help__subcmd__source"
                ;;
            *)
                ;;
        esac
    done

    case "${cmd}" in
        ns)
            opts="-h --license --help shell run edit homepage source search help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 1 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        ns__subcmd__edit)
            opts="-h --help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
        ns__subcmd__help)
            opts="shell run edit homepage source search help"
            if [[ ${cur} == -* || ${COMP_CWORD} -eq 2 ]] ; then
                COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
                return 0
            fi
            case "${prev}" in
                *)
                    COMPREPLY=()
                    ;;
            esac
            COMPREPLY=( $(compgen -W "${opts}" -- "${cur}") )
            return 0
            ;;
